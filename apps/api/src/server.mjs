import {readConfig} from './config.mjs';
import {createApp} from './app.mjs';
import {openDatabase,databaseAvailable} from './database.mjs';
import {createIdentityStore} from './identity-store.mjs';
import {readIdentityConfig,createTokenVerifier} from './token-verifier.mjs';
import {mappedVerifier} from './identity-runtime.mjs';
const {host,port}=readConfig();
const identity=readIdentityConfig();
if(identity&&!process.env.DATABASE_URL)throw new Error('Identity configuration requires database');
const db=await openDatabase(process.env.DATABASE_URL);
const store=db?createIdentityStore(db):null;
const server=createApp({verifyToken:mappedVerifier(createTokenVerifier(identity),store),dbHealth:()=>databaseAvailable(db),audit:store?.recordAudit,logger:entry=>console.log(JSON.stringify(entry))});
server.listen(port,host,()=>console.log(JSON.stringify({event:'api_started',host,port})));
for(const signal of ['SIGTERM','SIGINT'])process.once(signal,()=>{server.close(async()=>{if(db)await db.end();process.exit(0)});});
